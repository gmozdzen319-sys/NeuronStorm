-- Payment ownership stays the social identity; sender is the actual wallet.
ALTER TABLE payment_intents ADD COLUMN sender_wallet TEXT;
ALTER TABLE payment_intents ADD COLUMN send_operation_id TEXT UNIQUE REFERENCES passkey_native_operations_v2(id);
CREATE TABLE account_activity (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 address TEXT NOT NULL REFERENCES accounts(address),
 event_key TEXT NOT NULL UNIQUE,
 kind TEXT NOT NULL CHECK(kind IN ('like','tip','token')),
 actor TEXT,
 question_id TEXT REFERENCES questions(id),
 amount TEXT,
 symbol TEXT,
 tx_hash TEXT,
 created_at BIGINT NOT NULL,
 read_at BIGINT
);
CREATE INDEX account_activity_owner ON account_activity(address,created_at DESC);
CREATE TABLE token_notice_cursors (
 address TEXT NOT NULL REFERENCES accounts(address),
 wallet TEXT NOT NULL,
 token TEXT NOT NULL,
 block_number BIGINT NOT NULL,
 block_hash TEXT NOT NULL,
 PRIMARY KEY(address,wallet,token)
);
