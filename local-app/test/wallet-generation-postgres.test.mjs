import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createApp} from './database.mjs';
import {openDatabase} from '../db/database.mjs';
import {generateKeyPairSync} from 'node:crypto';
import {isoCBOR} from '@simplewebauthn/server/helpers';
import {prepareReceiveAssignments} from '../wallet/prepare-receive-v2-assignments.mjs';
test('v2 restart preserves identity/credential and immutable v1 evidence while isolating new assignment',{skip:!process.env.NEURON_TEST_DATABASE_URL},async()=>{
 const app=await createApp();let db,legacy;
 try{
  const name=(await app.db.prepare('SELECT current_database() AS name').get()).name;
  const url=new URL(process.env.NEURON_TEST_DATABASE_URL);url.pathname='/'+name;
  legacy=await openDatabase(url.href,{walletGeneration:1});
  const a='generation-test',credential='retained-passkey',old='0x0011111111111111111111111111111111111111';
  const jwk=generateKeyPairSync('ec',{namedCurve:'prime256v1'}).publicKey.export({format:'jwk'});
  const key=Buffer.from(isoCBOR.encode(new Map([[1,2],[3,-7],[-1,1],[-2,new Uint8Array(Buffer.from(jwk.x,'base64url'))],[-3,new Uint8Array(Buffer.from(jwk.y,'base64url'))]]))).toString('base64url');
  await app.db.prepare('INSERT INTO passkey_accounts VALUES($1,$2,1,NULL,$3,$4)').run(a,'retained-handle','neuronstorm.onrender.com','https://neuronstorm.onrender.com');
  await app.db.prepare('INSERT INTO passkey_credentials VALUES($1,$2,$3,7,$4,FALSE,1,1,NULL)').run(credential,a,key,'Existing device');
  await legacy.prepare('INSERT INTO passkey_clone_wallets VALUES($1,$2,$3,$4,$5,1)').run(a,credential,old,'key-fixture','v1-plan');
  await legacy.prepare("INSERT INTO passkey_clone_approvals(account_id,quote,commitment,expires_at,phase,approved) VALUES($1,'v1-quote','v1-commitment',1,'confirmed',FALSE)").run(a);
  if(!process.env.NEURON_TEST_DATABASE_URL)throw Error('This cutover regression requires native local PostgreSQL');
  db=await openDatabase(url.href,{walletGeneration:2});
  assert.equal(await db.prepare('SELECT * FROM passkey_clone_wallets WHERE account_id=$1').get(a),undefined);
  assert.equal(await db.prepare('SELECT * FROM passkey_clone_approvals WHERE account_id=$1').get(a),undefined);
  const saved=await db.prepare('SELECT * FROM passkey_credentials WHERE id=$1').get(credential);assert.equal(saved.counter,7);assert.equal(saved.account_id,a);
  const env={NS_WALLET_AUTO_ACTIVATE:'false',NS_WALLET_PROVISION_ENABLED:'false',NS_WALLET_SEND_ENABLED:'false'};
  for(const flag of Object.keys(env))await assert.rejects(prepareReceiveAssignments(db,{...env,[flag]:'true'}),/disabled/);
  const prepared=await prepareReceiveAssignments(db,env);
  assert.equal(prepared.broadcasts,0);assert.equal(prepared.spentQuai,'0');assert.equal(prepared.accounts[0].status,'reserved_v2');
  const fresh=prepared.accounts[0].address.toLowerCase();assert.notEqual(fresh,old);
  const repeated=await prepareReceiveAssignments(db,env);assert.equal(repeated.accounts[0].status,'existing_v2');assert.equal(repeated.accounts[0].address.toLowerCase(),fresh);
  const assigned=await db.prepare('SELECT * FROM passkey_clone_wallets WHERE account_id=$1').get(a);assert.equal(assigned.credential_id,credential);
  assert.equal((await db.prepare('SELECT * FROM passkey_credentials WHERE id=$1').get(credential)).public_key,key);
  await assert.rejects(db.prepare('UPDATE passkey_clone_wallets SET address=$1 WHERE account_id=$2').run(old,a),/immutable/);
  assert.equal((await db.prepare('SELECT * FROM passkey_v1_assignments WHERE account_id=$1').get(a)).address,old);
  assert.equal((await legacy.prepare('SELECT * FROM passkey_clone_approvals WHERE account_id=$1').get(a)).quote,'v1-quote');
  await db.close();db=await openDatabase(url.href,{walletGeneration:2});
  assert.equal((await db.prepare('SELECT * FROM passkey_clone_wallets WHERE account_id=$1').get(a)).address,fresh);
 }finally{await db?.close();await legacy?.close();await app.db.close();}
});
